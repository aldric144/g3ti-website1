// In-memory article store (in production, this would be a database)
const articlesStore: Article[] = [...sampleArticles]

export function getAllArticles(): Article[] {
  return articlesStore.filter(a => a.published).sort((a, b) => 
    new Date(b.date).getTime() - new Date(a.date).getTime()
  )
}

export function getArticleBySlug(slug: string): Article | undefined {
  return articlesStore.find(a => a.slug === slug)
}

export function getArticlesByCategory(category: ArticleCategory): Article[] {
  return articlesStore
    .filter(a => a.category === category && a.published)
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
}

export function addArticle(article: Article): void {
  articlesStore.push(article)
}

export function updateArticle(id: string, updates: Partial<Article>): boolean {
  const index = articlesStore.findIndex(a => a.id === id)
  if (index === -1) return false
  articlesStore[index] = { ...articlesStore[index], ...updates }
  return true
}

export function deleteArticle(id: string): boolean {
  const index = articlesStore.findIndex(a => a.id === id)
  if (index === -1) return false
  articlesStore.splice(index, 1)
  return true
}

export function getArticleCount(): number {
  return articlesStore.length
}

export function getPublishedCount(): number {
  return articlesStore.filter(a => a.status === 'published').length
}

export function getDraftCount(): number {
  return articlesStore.filter(a => a.status === 'draft').length
}

export function getScheduledCount(): number {
  return articlesStore.filter(a => a.status === 'scheduled').length
}

